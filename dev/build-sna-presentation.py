#!/usr/bin/env python3
"""Extract presentation evidence without altering the verified research dataset.
Usage: python dev/build-sna-presentation.py report.docx distances.xlsx graph.gephi
Requires openpyxl and Pillow. Coordinates are measured from report Figure 6,
not generated by a layout algorithm and NOT claimed as the missing CONCOR figure.
"""
import hashlib, json, sys, zipfile, struct
from pathlib import Path
import openpyxl
from PIL import Image
from io import BytesIO
report, distance, gephi = map(Path, sys.argv[1:4])
data = json.loads(Path('lab/sna/data.json').read_text())
with zipfile.ZipFile(report) as z:
    raw = z.read('word/media/image69.png')
    def wmf_text(blob):
        # META_EXTTEXTOUT strings are evidence in the embedded original figures.
        offset=(22 if blob[:4]==bytes.fromhex('d7cdc69a') else 0)+18
        text=[]
        while offset+6<=len(blob):
            size,fn=struct.unpack_from('<IH',blob,offset)
            if size<3:break
            v=blob[offset+6:offset+size*2]
            if fn==0xa32 and len(v)>=8:
                _,_,n,opts=struct.unpack_from('<hhhh',v)
                start=8+(8 if opts&6 else 0)
                text.append(v[start:start+n].decode('gbk',errors='replace'))
            offset+=size*2
        return ' '.join(text)
    qap_text=wmf_text(z.read('word/media/image80.wmf'))
    assert all(v in qap_text for v in ['0.6686','0.083663','0.54025','0.765208','0.091991'])
    binary_text=wmf_text(z.read('word/media/image68.wmf'))
    assert b'\xb3' in z.read('word/media/image68.wmf') # Symbol-font greater-than-or-equal.

im = Image.open(BytesIO(raw)).convert('RGB')
# Label-to-position mapping read from the named nodes of original Figure 6.
# Pixel centers are snapped to measured blue marker components below.
approx = [(1368,903),(1046,818),(1130,505),(902,487),(762,885),(1428,706),(1183,1048),(1910,721),(1389,501),(909,1085),(784,668),(1838,190),(1770,1328),(443,1379),(2045,1138),(1061,44),(1518,73),(2191,908),(1133,1500),(174,1134),(469,142),(1546,1443),(2097,392),(53,895),(45,598),(212,365)]
blue = {(x,y) for y in range(im.height) for x in range(im.width) if (lambda c: c[0]<30 and 90<c[1]<170 and c[2]>170)(im.getpixel((x,y)))}
centers=[]
while blue:
    q=[blue.pop()]; comp=[]
    while q:
        x,y=q.pop();comp.append((x,y))
        for p in [(x+1,y),(x-1,y),(x,y+1),(x,y-1)]:
            if p in blue:blue.remove(p);q.append(p)
    if len(comp)>100:
        centers.append([(min(p[k] for p in comp)+max(p[k] for p in comp))/2 for k in [0,1]])
assert len(centers)==26
matched=[min(centers,key=lambda c:(c[0]-a[0])**2+(c[1]-a[1])**2) for a in approx]
assert len({tuple(p) for p in matched})==26
assert all((p[0]-a[0])**2+(p[1]-a[1])**2<100 for p,a in zip(matched,approx))
# Uniform similarity transform only; preserves original relative geometry.
scale=min(700/(max(p[0] for p in matched)-min(p[0] for p in matched)),440/(max(p[1] for p in matched)-min(p[1] for p in matched)))
cx=(min(p[0] for p in matched)+max(p[0] for p in matched))/2;cy=(min(p[1] for p in matched)+max(p[1] for p in matched))/2
positions=[[round(410+(p[0]-cx)*scale,6),round(280+(p[1]-cy)*scale,6)] for p in matched]
w=openpyxl.load_workbook(distance,data_only=False);values=[c.value for row in w['Sheet1'].iter_rows(min_row=2,max_row=27,min_col=2,max_col=27) for c in row]
assert all(v is None for v in values),'Actual distance data supplied: inspect before using missing status'
assert not any(abs(data['weights'][i][j]-data['columnMeans'][j])<1e-12 for i in range(26) for j in range(26) if i!=j)
out={'sources':[{'file':p.name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in [report,distance,gephi]],'layout':{'source':'Report Figure 6, word/media/image69.png','imageSha256':hashlib.sha256(raw).hexdigest(),'pixelCenters':matched,'positions':positions,'transform':{'scale':scale,'center':[cx,cy]},'concorReferenceAvailable':False},'distance':{'available':False,'sheet':'Sheet1','range':'B2:AA27','emptyCells':676,'coordinateRows':26,'reason':'Only geographic coordinates and an empty matrix template; no transport-cost observations.'},'cooperation':{'available':False,'reason':'No complete 26×26 source matrix found. Gephi workspace 图书馆微博(1) contains only 18 node records; no mapping of absent schools to zero is justified.'},'qapReport':{'source':'Report QAP results table, word/media/image80.wmf','distanceP':0.083663,'cooperationP':0.0005,'r2':0.6686,'coefficientType':'unstandardized','excelDistancePConflict':0.073663},'threshold':{'comparison':'>=','evidence':'Report equation after Figure 5: Symbol font byte B3 (greater-than-or-equal); 0 branch <.','denominator':26,'diagonalIncluded':True,'removeSelfLoops':True,'offDiagonalEqualsMean':0}}
Path('lab/sna/presentation.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n')
print('Verified: 26 source-image positions; 676 empty distance cells; no threshold-equality cases.')

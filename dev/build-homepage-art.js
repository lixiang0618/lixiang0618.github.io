/* Reuse the actual Lab illustrations, in both languages, without its captions. */
const fs = require('node:fs');
const path = require('node:path');
const {parseDocument} = require('htmlparser2');
const {findAll} = require('domutils');
const serialize = require('dom-serializer').default;
const root = path.resolve(__dirname, '..');
const result = {};
for (const [locale, file] of [['en', 'lab.html'], ['zh', 'zh/lab.html']]) {
  const doc = parseDocument(fs.readFileSync(path.join(root, file), 'utf8'));
  result[locale] = {};
  for (const art of findAll(n => !!n.attribs?.['data-gallery-art'], doc.children)) {
    const svg = art.children.find(n => n.name === 'svg');
    if (svg) result[locale][art.attribs['data-gallery-art']] = serialize(svg);
  }
}
fs.writeFileSync(path.join(root, 'js/profile-art.js'), '/* Generated by dev/build-homepage-art.js from the existing Lab artwork. */\nwindow.ProfileProjectArt = ' + JSON.stringify(result) + ';\n');
console.log('Prepared Lab artwork:', Object.keys(result.en).join(', '));
